def font(run, size=10.5, bold=False, color=BLACK):
    run.font.name = "Microsoft YaHei"
    run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), "Microsoft YaHei")
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = color


def shade(cell, fill):
    pr = cell._tc.get_or_add_tcPr()
    node = pr.find(qn("w:shd"))
    if node is None:
        node = OxmlElement("w:shd")
        pr.append(node)
    node.set(qn("w:fill"), fill)


def borders(cell):
    pr = cell._tc.get_or_add_tcPr()
    box = pr.find(qn("w:tcBorders"))
    if box is None:
        box = OxmlElement("w:tcBorders")
        pr.append(box)
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        node = box.find(qn(f"w:{edge}"))
        if node is None:
            node = OxmlElement(f"w:{edge}")
            box.append(node)
        node.set(qn("w:val"), "single")
        node.set(qn("w:sz"), "4")
        node.set(qn("w:color"), BORDER)


def margins(cell, v=110, h=120):
    pr = cell._tc.get_or_add_tcPr()
    mar = pr.find(qn("w:tcMar"))
    if mar is None:
        mar = OxmlElement("w:tcMar")
        pr.append(mar)
    for side, value in (("top", v), ("bottom", v), ("start", h), ("end", h)):
        node = mar.find(qn(f"w:{side}"))
        if node is None:
            node = OxmlElement(f"w:{side}")
            mar.append(node)
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")


def repeat_header(row):
    pr = row._tr.get_or_add_trPr()
    node = OxmlElement("w:tblHeader")
    node.set(qn("w:val"), "true")
    pr.append(node)


