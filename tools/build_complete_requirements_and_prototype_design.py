def heading(doc, text, level=1):
    return doc.add_paragraph(text, style=f"Heading {level}")


def para(doc, text, lead=None):
    p = doc.add_paragraph()
    if lead and text.startswith(lead):
        font(p.add_run(lead), bold=True)
        font(p.add_run(text[len(lead):]))
    else:
        font(p.add_run(text))
    return p


def bullets(doc, items):
    for item in items:
        p = doc.add_paragraph(style="List Bullet")
        font(p.add_run(item))


def numbered(doc, items):
    for i, item in enumerate(items, 1):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(0.55)
        p.paragraph_format.first_line_indent = Cm(-0.55)
        font(p.add_run(f"{i}. {item}"))


def table(doc, headers, rows, widths=None, small=9.0):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    repeat_header(t.rows[0])
    for i, text in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = str(text)
        shade(c, NAVY)
        borders(c)
        margins(c)
        c.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        if widths:
            c.width = Cm(widths[i])
        for p in c.paragraphs:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            for r in p.runs:
                font(r, 9.3, True, RGBColor(255, 255, 255))
    for ridx, row in enumerate(rows):
        cells = t.add_row().cells
        for i, value in enumerate(row):
            c = cells[i]
            c.text = str(value)
            borders(c)
            margins(c)
            c.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if widths:
                c.width = Cm(widths[i])
            if ridx % 2:
                shade(c, ALT)
            for p in c.paragraphs:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER if len(str(value)) < 18 else WD_ALIGN_PARAGRAPH.LEFT
                for r in p.runs:
                    font(r, small)
    spacer = doc.add_paragraph()
    spacer.paragraph_format.space_after = Pt(1)
    return t


